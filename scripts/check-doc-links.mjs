/**
 * Broken-link and broken-anchor check for the built docs site.
 *
 * Nothing in this repo caught an in-site link that pointed at a heading which
 * does not exist. `cli.mdx` carried two links to
 * `/docmeta/reference/output-and-exit-codes/#json` for months: the page renders
 * no `id="json"` — its JSON content sits inside a Starlight `<Tabs>` block under
 * `## Output formats` — so both links silently landed at the top of the page.
 * Nothing failed. A reader following one just quietly did not arrive.
 *
 * That is the failure mode this guards: not a 404, which someone notices, but a
 * link that resolves to the right *page* and the wrong *place*. The drift checks
 * next to this one (`docs:check-cli`, `-api`, `-action`) all compare a page to a
 * source of truth; a link has no source of truth other than the rendered site,
 * so this reads the built HTML rather than the MDX.
 *
 * Reading the build, not the source, is also what makes anchors checkable at
 * all: heading ids are generated by the Markdown pipeline (slugified, deduped),
 * and Starlight adds its own (`_top`, the tab ids). Only the output knows them.
 *
 * What counts as internal: any href that resolves inside the site's base path.
 * External URLs, `mailto:`, and asset files are another system's problem — a
 * link checker that hits the network is a check that fails when someone else's
 * site is down, which is the lesson `check-published-schemas.mjs` records.
 *
 * Usage:
 *   node scripts/check-doc-links.mjs [path/to/docs/dist]
 * Requires `cd docs && npm run build` first (reads the rendered HTML).
 * Exit 0 = every internal link and anchor resolves, 1 = broken links, 2 = setup.
 */
import { readdirSync, readFileSync, existsSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIST = path.resolve(ROOT, process.argv[2] ?? "docs/dist");

/** The site's base path, from docs/astro.config.mjs. */
const BASE = "/docmeta";

if (!existsSync(DIST) || !statSync(DIST).isDirectory()) {
  console.error(
    `docs:check-links: no built site at ${path.relative(ROOT, DIST).replace(/\\/g, "/")}.\n` +
      `Run \`cd docs && npm run build\` first — this check reads the rendered HTML,\n` +
      `because heading ids only exist after the Markdown pipeline has generated them.`,
  );
  process.exit(2);
}

// ---------------------------------------------------------------------------
// 1. Collect every rendered page and the ids it actually carries.
// ---------------------------------------------------------------------------
/** @type {string[]} */
const pages = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(abs);
    else if (entry.name.endsWith(".html")) pages.push(abs);
  }
};
walk(DIST);

if (pages.length === 0) {
  console.error(`docs:check-links: ${DIST} contains no .html files.`);
  process.exit(2);
}

/** Rendered page path (posix, relative to dist) -> set of ids on that page. */
const idsByPage = new Map();
/** Every rendered page path, for existence checks. */
const rendered = new Set();

const relFromDist = (abs) => path.relative(DIST, abs).replace(/\\/g, "/");

for (const abs of pages) {
  const rel = relFromDist(abs);
  rendered.add(rel);
  const html = readFileSync(abs, "utf8");
  const ids = new Set();
  // Both spellings: `id` is what headings use, `name` is still legal on <a>.
  for (const m of html.matchAll(/\s(?:id|name)="([^"]+)"/g)) ids.add(m[1]);
  idsByPage.set(rel, ids);
}

// ---------------------------------------------------------------------------
// 2. Resolve every internal href to a rendered page (and, if it has one, an id).
// ---------------------------------------------------------------------------

/**
 * Map a site-absolute URL path to the file the server would return.
 * `/docmeta/reference/cli/` -> `reference/cli/index.html`.
 */
function toRenderedPath(urlPath) {
  let p = urlPath;
  if (p.startsWith(BASE)) p = p.slice(BASE.length);
  p = p.replace(/^\/+/, "");
  if (p === "") return "index.html";
  if (p.endsWith(".html")) return p;
  return `${p.replace(/\/+$/, "")}/index.html`;
}

/** Links to files the site serves but does not render as pages. */
const ASSET = /\.(json|svg|png|jpe?g|gif|webp|ico|css|js|mjs|txt|xml|zip|pdf|woff2?)$/i;

const problems = [];
let checkedLinks = 0;
let checkedAnchors = 0;

for (const abs of pages) {
  const fromRel = relFromDist(abs);
  const html = readFileSync(abs, "utf8");
  for (const m of html.matchAll(/<a\b[^>]*\shref="([^"]*)"/g)) {
    const raw = m[1];
    if (!raw || raw.startsWith("//")) continue;
    // Another origin, or another protocol, is not ours to verify.
    if (/^[a-z][a-z0-9+.-]*:/i.test(raw)) continue;

    const hashAt = raw.indexOf("#");
    const rawPath = hashAt === -1 ? raw : raw.slice(0, hashAt);
    const rawFrag = hashAt === -1 ? "" : raw.slice(hashAt + 1);
    // Starlight emits a few control anchors with no target of their own.
    if (rawPath === "" && rawFrag === "") continue;

    let fragment;
    try {
      fragment = decodeURIComponent(rawFrag);
    } catch {
      fragment = rawFrag;
    }

    // A bare `#frag` is a link into the page it sits on.
    const targetRel =
      rawPath === ""
        ? fromRel
        : toRenderedPath(
            rawPath.startsWith("/")
              ? rawPath
              : path.posix.resolve(`/${path.posix.dirname(fromRel)}`, rawPath),
          );

    if (ASSET.test(targetRel.replace(/\/index\.html$/, ""))) continue;

    checkedLinks += 1;
    if (!rendered.has(targetRel)) {
      problems.push(`${fromRel}\n      -> ${raw}\n      no such page: ${targetRel}`);
      continue;
    }
    if (fragment === "") continue;

    checkedAnchors += 1;
    const ids = idsByPage.get(targetRel);
    if (!ids?.has(fragment)) {
      problems.push(
        `${fromRel}\n      -> ${raw}\n` +
          `      page exists, but it renders no id="${fragment}" — the link lands at the top`,
      );
    }
  }
}

// ---------------------------------------------------------------------------
// 3. Report.
// ---------------------------------------------------------------------------
if (problems.length) {
  console.error(
    `docs:check-links: ${problems.length} broken internal link${problems.length === 1 ? "" : "s"}:`,
  );
  for (const p of problems) console.error(`  - ${p}`);
  console.error(
    `\nA link to a page that exists but an anchor that does not is the quiet one:\n` +
      `it resolves, so nothing 404s, and the reader simply lands at the top of the\n` +
      `page instead of at the thing you sent them to. Fix the href, or give the\n` +
      `target a real heading, then re-run \`npm run docs:check-links\`.`,
  );
  process.exit(1);
}

console.log(
  `docs:check-links: ${checkedLinks} internal links (${checkedAnchors} with anchors) across ${pages.length} pages all resolve ✓`,
);
